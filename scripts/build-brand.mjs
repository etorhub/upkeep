/**
 * Builds every Upkeep brand asset from the geometry in branding/paths.json.
 *
 *   npm run build:brand
 *
 * Writes SVGs to branding/, PNGs to custom_components/upkeep/brand/ (the folder
 * Home Assistant and HACS read), and the sidebar icon path to src/brand/paths.ts.
 * Outputs are committed, so CI never has to run this.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const brandingDir = join(root, 'branding');
const brandDir = join(root, 'custom_components', 'upkeep', 'brand');
const paths = JSON.parse(readFileSync(join(brandingDir, 'paths.json'), 'utf8'));

const ACCENT = '#11a387';
const INK = { light: '#17303a', dark: '#eef3f4' };

// The mark lives in a 256 x 256 box. These two shapes are the whole logo.
const ROOF = 'M36 114 L128 40 L220 114';
const CUP = 'M62 136 V158 A66 66 0 0 0 194 158 V136';
// Ink extent of the mark (stroke width 28 included).
const BOX = { x: 22, y: 26, w: 212, h: 212 };

const mark = (
  ink
) => `<g fill="none" stroke-linecap="round" stroke-linejoin="round" stroke-width="28">
    <path d="${ROOF}" stroke="${ink}"/>
    <path d="${CUP}" stroke="${ACCENT}" stroke-opacity="0.28"/>
    <path d="${CUP}" stroke="${ACCENT}" pathLength="100" stroke-dasharray="64 100"/>
  </g>`;

const svg = (viewBox, body, title = 'Upkeep') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${title}">
  <title>${title}</title>
  ${body}
</svg>
`;

// Wordmark geometry, in mark units: 54px type next to a 60px mark, 16px apart.
const UNIT = 256 / 60;
const FONT_SIZE = 54 * UNIT;
const SCALE = FONT_SIZE / paths.wordmark.unitsPerEm;
const GAP = 16 * UNIT;
const BASELINE = 190;
const TEXT_X = BOX.x + BOX.w + GAP - 8;
const TEXT_W = paths.wordmark.advance * SCALE;
const PAD = 24;

const wordmark = (ink) =>
  `<path transform="translate(${TEXT_X.toFixed(2)} ${BASELINE}) scale(${SCALE.toFixed(5)})" d="${paths.wordmark.d}" fill="${ink}"/>`;

const logoBox = {
  x: BOX.x - PAD,
  y: BOX.y - PAD,
  w: TEXT_X + TEXT_W - BOX.x + PAD * 2,
  h: BOX.h + PAD * 2,
};
const logoViewBox = `${logoBox.x} ${logoBox.y} ${Math.ceil(logoBox.w)} ${logoBox.h}`;
// Square canvas centred on the mark, used for app icons.
const iconViewBox = `${BOX.x + BOX.w / 2 - 128} ${BOX.y + BOX.h / 2 - 128} 256 256`;

const files = {
  'mark.svg': svg(iconViewBox, mark(INK.light)),
  'mark-dark.svg': svg(iconViewBox, mark(INK.dark)),
  'logo.svg': svg(logoViewBox, `${mark(INK.light)}\n  ${wordmark(INK.light)}`),
  'logo-dark.svg': svg(logoViewBox, `${mark(INK.dark)}\n  ${wordmark(INK.dark)}`),
  'mark-mono.svg': svg(
    iconViewBox,
    `<path fill="currentColor" fill-rule="nonzero" d="${paths.mono}"/>`
  ),
  'social-preview.svg': svg(
    '0 0 1280 640',
    `<rect width="1280" height="640" fill="#111418"/>
  <g transform="translate(${(640 - (logoBox.w * 0.78) / 2 - logoBox.x * 0.78).toFixed(1)} ${(320 - 0.78 * (logoBox.y + logoBox.h / 2)).toFixed(1)}) scale(0.78)">
    ${mark(INK.dark)}
    ${wordmark(INK.dark)}
  </g>`
  ),
};
for (const [name, content] of Object.entries(files)) {
  writeFileSync(join(brandingDir, name), content);
}

// Sidebar icon: Home Assistant custom icon sets take a single filled path.
writeFileSync(
  join(root, 'src', 'brand', 'paths.ts'),
  `// Generated by scripts/build-brand.mjs. Do not edit.
export const MARK_VIEWBOX = '${iconViewBox}';
export const MARK_MONO_PATH =
  '${paths.mono}';
`
);

// Rasterise with the Chromium that Playwright ships. Playwright is not a project
// dependency: use a global install or `npm install --no-save playwright`.
let chromium;
try {
  ({ chromium } = createRequire(import.meta.url)('playwright'));
} catch {
  console.error('build:brand needs Playwright (npm install --no-save playwright).');
  process.exit(1);
}
const browser = await chromium.launch();
const page = await browser.newPage();

async function png(name, content, width, height, outDir = brandDir) {
  mkdirSync(outDir, { recursive: true });
  await page.setViewportSize({ width, height });
  await page.setContent(
    `<style>html,body{margin:0;background:transparent}svg{display:block;width:${width}px;height:${height}px}</style>${content}`
  );
  await page.screenshot({ path: join(outDir, name), omitBackground: true });
}

const ratio = Math.ceil(logoBox.w) / logoBox.h;
for (const [suffix, factor] of [
  ['', 1],
  ['@2x', 2],
]) {
  const side = 256 * factor;
  const logoW = Math.round(256 * ratio * factor);
  await png(`icon${suffix}.png`, files['mark.svg'], side, side);
  await png(`dark_icon${suffix}.png`, files['mark-dark.svg'], side, side);
  await png(`logo${suffix}.png`, files['logo.svg'], logoW, side);
  await png(`dark_logo${suffix}.png`, files['logo-dark.svg'], logoW, side);
}
await png('social-preview.png', files['social-preview.svg'], 1280, 640, brandingDir);
await browser.close();
console.log(
  'Brand assets written to branding/, custom_components/upkeep/brand/ and src/brand/paths.ts'
);
